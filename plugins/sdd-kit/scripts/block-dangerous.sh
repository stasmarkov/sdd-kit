#!/bin/bash
#
# PreToolUse hook (Bash matcher) - Block dangerous commands and shell or file writes to the stack trust store
#
# Receives JSON on stdin with tool_name and tool_input fields; agent_id is present when the
# call comes from a subagent (workflow agents included).
# Exit 0 to allow, exit 2 to block (stderr shown to Claude).
#

set -euo pipefail

INPUT=$(cat)

# Only /stack-trust, run by the user in the main session, may change
# host trust store (<home>/<host config dir>/sdd-kit/trusted-stacks.json, <home> from the OS user database):
# an approval lets a stack manifest's commands run on this machine, so an agent acting on repo content
# must not grant one. The file name catches any location; the generated list names every host's store.
STORE_NAME='trusted-stacks.json'
STORE_FIX="Only /stack-trust may change the trust store, after the user reviews the manifest. Fix: ask the user to run /stack-trust."
# --- trust stores: begin (generated by tools/gen-stacks.mjs from src/adapters/hosts.json; do not edit) ---
STORE_PATHS=('.claude/sdd-kit/trusted-stacks.json' '.codex/sdd-kit/trusted-stacks.json' '.cursor/sdd-kit/trusted-stacks.json')
# --- trust stores: end ---

# A read-only tool never writes, so it is never blocked here, even when it names the store (the Detect
# prompt on Codex and Cursor reads the store with such a tool).
TOOL_NAME=$(echo "$INPUT" | jq -r '.tool_name // empty' | tr '[:upper:]' '[:lower:]')
case "$TOOL_NAME" in
    read|grep|glob|ls|view|notebookread|webfetch|websearch|read_file|list_dir|file_search|grep_search|codebase_search)
        exit 0
        ;;
esac

# A file write names its target in file_path (Write, Edit, and Codex or Cursor patches the hook
# dispatcher splits per file). Normalize ~, $HOME, ${HOME}, ./ and .. so every spelling of the
# store path is compared the same way, then match on the generated path suffixes.
FILE_PATH=$(echo "$INPUT" | jq -r '.tool_input.file_path // empty')
if [[ -n "$FILE_PATH" ]]; then
    # Case-insensitive, with repeated slashes squeezed: a double slash or a case variant still opens the real file.
    NORMALIZED=$(echo "$FILE_PATH" | tr '[:upper:]' '[:lower:]' | tr -s '/' | sed -E 's#^(~|\$home|\$\{home\})/#/#; s#(^|/)(\./)+#\1#g')
    # Whatever directory spelling reaches the file, the name itself is the store's.
    if [[ "${NORMALIZED##*/}" == "$STORE_NAME" ]]; then
        echo "Blocked: file write to the stack trust store. $STORE_FIX" >&2
        exit 2
    fi
    while [[ "$NORMALIZED" =~ (^|/)[^/]+/\.\./ ]]; do
        NORMALIZED=$(echo "$NORMALIZED" | sed -E 's#(^|/)[^/]+/\.\./#\1#')
    done
    for STORE_PATH in "${STORE_PATHS[@]}"; do
        if [[ "$NORMALIZED" == "$STORE_PATH" || "$NORMALIZED" == */"$STORE_PATH" ]]; then
            echo "Blocked: file write to the stack trust store. $STORE_FIX" >&2
            exit 2
        fi
    done
fi

COMMAND=$(echo "$INPUT" | jq -r '.tool_input.command // empty')

if [[ -z "$COMMAND" ]]; then
    exit 0
fi

# The shell rebuilds a quoted or escaped word (--appro""ve, trusted-stacks\.json) after this check has run,
# so the store and approval checks also read the command with quotes and backslashes removed.
# This shell check is best-effort hardening, not a boundary: see src/hooks/README.md.
PLAIN=$(printf '%s' "$COMMAND" | tr -d "'\"\\\\")

AGENT_ID=$(echo "$INPUT" | jq -r '.agent_id // empty')
# Codex and Cursor payloads carry no agent_id, and a hook never has a human at a terminal, so on those
# hosts (SDD_HOST is set by the hook dispatcher) any --approve is refused: the user runs it in their own terminal.
NON_CLAUDE_HOST=''
if [[ -n "${SDD_HOST:-}" && "${SDD_HOST}" != "claude" ]]; then
    NON_CLAUDE_HOST=1
fi
if [[ ( -n "$AGENT_ID" || -n "$NON_CLAUDE_HOST" ) ]] && echo "$PLAIN" | grep -qE 'trust-store\.mjs' && echo "$PLAIN" | grep -qE -- '--approve'; then
    echo "Blocked: a subagent or an agent on a hook-dispatched host tried to approve a stack manifest. Approve it in your own terminal. $STORE_FIX" >&2
    exit 2
fi

# Reading the store (cat, jq, head, test -f) stays allowed: Detect returns its text to the workflow.
# Anything that could write it is refused: an output redirect other than to /dev/null or a
# descriptor, a command that copies, moves, deletes or edits in place, or inline code (-e, -c, --eval).
TOUCHES_STORE=0
if echo "$PLAIN" | grep -qiF "$STORE_NAME"; then
    TOUCHES_STORE=1
fi
for STORE_PATH in "${STORE_PATHS[@]}"; do
    if echo "$PLAIN" | grep -qiF "$STORE_PATH"; then
        TOUCHES_STORE=1
    fi
done
# A glob in the last path segment that matches the store's file name (trusted-stack?.json) names it too.
# At least six literal characters are required, so a bare * does not count.
STORE_LOWER=$(printf '%s' "$STORE_NAME" | tr '[:upper:]' '[:lower:]')
set -f
for WORD in $(printf '%s' "$PLAIN" | tr '[:upper:]' '[:lower:]'); do
    case "$WORD" in
        *[\*\?\[]*) ;;
        *) continue ;;
    esac
    BASE=${WORD##*/}
    LITERAL=$(printf '%s' "$BASE" | tr -d '*?[]')
    if [[ ${#LITERAL} -ge 6 ]]; then
        case "$STORE_LOWER" in
            $BASE) TOUCHES_STORE=1 ;;
        esac
    fi
done
set +f
if [[ "$TOUCHES_STORE" -eq 1 ]]; then
    STRIPPED=$(echo "$PLAIN" | sed -E 's#[0-9]*>>?[[:space:]]*/dev/null##g; s#[0-9]*>&[0-9-]##g; s#(test|\[)[[:space:]]+-[a-z]([[:space:]])#\1 \2#g')
    if echo "$STRIPPED" | grep -qE '>' \
        || echo "$STRIPPED" | grep -qE '(^|[^[:alnum:]_.-])(tee|cp|mv|rm|ln|install|rsync|truncate|dd|touch|chmod|chown|ed|ex|vi|vim|nano)([[:space:]]|$)' \
        || echo "$STRIPPED" | grep -qE '[[:space:]](-e|-c|-p|--eval|--print)([[:space:]]|$)' \
        || echo "$STRIPPED" | grep -qE '(^|[[:space:]])(sed|gsed)[[:space:]].*-i'; then
        echo "Blocked: shell command that could write the stack trust store. $STORE_FIX" >&2
        exit 2
    fi
fi

# Keep patterns portable (POSIX classes, no empty alternatives): macOS grep rejects
# `(a|)`, and a grep error inside `if` reads as "no match" — silently allowing the command.

# Block rm targeting / or /* (but not ordinary absolute paths like /tmp/x)
if echo "$COMMAND" | grep -qE 'rm[[:space:]]+(-[-a-zA-Z]+[[:space:]]+)*/\*?([[:space:]]|$|[;&|])'; then
    echo "Blocked: recursive delete of root filesystem is not allowed." >&2
    exit 2
fi

# Block force push to main/master
if echo "$COMMAND" | grep -qE 'git[[:space:]]+push[[:space:]]+.*--force.*[[:space:]]+(main|master)'; then
    echo "Blocked: force push to main/master. Use a feature branch instead." >&2
    exit 2
fi
if echo "$COMMAND" | grep -qE 'git[[:space:]]+push[[:space:]]+-f[[:space:]]+.*[[:space:]]+(main|master)'; then
    echo "Blocked: force push to main/master. Use a feature branch instead." >&2
    exit 2
fi

# Block drop database
if echo "$COMMAND" | grep -qiE '(drop[[:space:]]+database|dropdb)[[:space:]]'; then
    echo "Blocked: dropping databases requires manual confirmation." >&2
    exit 2
fi

exit 0
