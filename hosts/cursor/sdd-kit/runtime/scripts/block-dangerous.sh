#!/bin/bash
#
# PreToolUse hook (Bash matcher) - Block dangerous commands and shell or file writes to the stack trust store
#
# Receives JSON on stdin with tool_name and tool_input fields; agent_id is present when the
# call comes from a subagent (workflow agents included).
# Exit 0 to allow, exit 2 to block (stderr shown to Claude).
#

set -euo pipefail

INPUT=$(cat)

# Only /stack-trust, run by the user in the main session, may change
# host trust store (<home>/<host config dir>/sdd-kit/trusted-stacks.json, <home> from the OS user database):
# an approval lets a stack manifest's commands run on this machine, so an agent acting on repo content
# must not grant one. The file name catches any location; the generated list names every host's store.
STORE_NAME='trusted-stacks.json'
STORE_FIX="Only /stack-trust may change the trust store, after the user reviews the manifest. Fix: ask the user to run /stack-trust."
# --- trust stores: begin (generated by tools/gen-stacks.mjs from src/adapters/hosts.json; do not edit) ---
STORE_PATHS=('.claude/sdd-kit/trusted-stacks.json' '.codex/sdd-kit/trusted-stacks.json' '.cursor/sdd-kit/trusted-stacks.json')
# --- trust stores: end ---

# A read-only tool never writes, so it is never blocked here, even when it names the store (the Detect
# prompt on Codex and Cursor reads the store with such a tool).
TOOL_NAME=$(echo "$INPUT" | jq -r '.tool_name // empty' | tr '[:upper:]' '[:lower:]')
case "$TOOL_NAME" in
    read|grep|glob|ls|view|notebookread|webfetch|websearch|read_file|list_dir|file_search|grep_search|codebase_search)
        exit 0
        ;;
esac

# A file write names its target in file_path (Write, Edit, and Codex or Cursor patches the hook
# dispatcher splits per file). Normalize ~, $HOME, ${HOME}, ./ and .. so every spelling of the
# store path is compared the same way, then match on the generated path suffixes.
FILE_PATH=$(echo "$INPUT" | jq -r '.tool_input.file_path // empty')
if [[ -n "$FILE_PATH" ]]; then
    # Case-insensitive, with repeated slashes squeezed: a double slash or a case variant still opens the real file.
    NORMALIZED=$(echo "$FILE_PATH" | tr '[:upper:]' '[:lower:]' | tr -s '/' | sed -E 's#^(~|\$home|\$\{home\})/#/#; s#(^|/)(\./)+#\1#g')
    # Whatever directory spelling reaches the file, the name itself is the store's.
    if [[ "${NORMALIZED##*/}" == "$STORE_NAME" ]]; then
        echo "Blocked: file write to the stack trust store. $STORE_FIX" >&2
        exit 2
    fi
    while [[ "$NORMALIZED" =~ (^|/)[^/]+/\.\./ ]]; do
        NORMALIZED=$(echo "$NORMALIZED" | sed -E 's#(^|/)[^/]+/\.\./#\1#')
    done
    for STORE_PATH in "${STORE_PATHS[@]}"; do
        if [[ "$NORMALIZED" == "$STORE_PATH" || "$NORMALIZED" == */"$STORE_PATH" ]]; then
            echo "Blocked: file write to the stack trust store. $STORE_FIX" >&2
            exit 2
        fi
    done
fi

COMMAND=$(echo "$INPUT" | jq -r '.tool_input.command // empty')

if [[ -z "$COMMAND" ]]; then
    exit 0
fi

# The shell rebuilds a quoted or escaped word (--appro""ve, trusted-stacks\.json) after this check has run,
# so the store and approval checks also read the command with quotes and backslashes removed.
# This shell check is best-effort hardening, not a boundary: see src/hooks/README.md.
PLAIN=$(printf '%s' "$COMMAND" | tr -d "'\"\\\\")

AGENT_ID=$(echo "$INPUT" | jq -r '.agent_id // empty')
# Codex and Cursor payloads carry no agent_id, and a hook never has a human at a terminal, so on those
# hosts (SDD_HOST is set by the hook dispatcher) any --approve is refused: the user runs it in their own terminal.
NON_CLAUDE_HOST=''
if [[ -n "${SDD_HOST:-}" && "${SDD_HOST}" != "claude" ]]; then
    NON_CLAUDE_HOST=1
fi
if [[ ( -n "$AGENT_ID" || -n "$NON_CLAUDE_HOST" ) ]] && echo "$PLAIN" | grep -qE 'trust-store\.mjs' && echo "$PLAIN" | grep -qE -- '--approve'; then
    echo "Blocked: a subagent or an agent on a hook-dispatched host tried to approve a stack manifest. Approve it in your own terminal. $STORE_FIX" >&2
    exit 2
fi

# Reading the store (cat, jq, head, test -f) stays allowed: Detect returns its text to the workflow.
# Anything that could write it is refused: an output redirect other than to /dev/null or a
# descriptor, a command that copies, moves, deletes or edits in place, or inline code (-e, -c, --eval).
TOUCHES_STORE=0
if echo "$PLAIN" | grep -qiF "$STORE_NAME"; then
    TOUCHES_STORE=1
fi
for STORE_PATH in "${STORE_PATHS[@]}"; do
    if echo "$PLAIN" | grep -qiF "$STORE_PATH"; then
        TOUCHES_STORE=1
    fi
done
# A glob in the last path segment that matches the store's file name (trusted-stack?.json) names it too.
# At least six literal characters are required, so a bare * does not count.
STORE_LOWER=$(printf '%s' "$STORE_NAME" | tr '[:upper:]' '[:lower:]')
set -f
for WORD in $(printf '%s' "$PLAIN" | tr '[:upper:]' '[:lower:]'); do
    case "$WORD" in
        *[\*\?\[]*) ;;
        *) continue ;;
    esac
    BASE=${WORD##*/}
    LITERAL=$(printf '%s' "$BASE" | tr -d '*?[]')
    if [[ ${#LITERAL} -ge 6 ]]; then
        case "$STORE_LOWER" in
            $BASE) TOUCHES_STORE=1 ;;
        esac
    fi
done
set +f
if [[ "$TOUCHES_STORE" -eq 1 ]]; then
    STRIPPED=$(echo "$PLAIN" | sed -E 's#[0-9]*>>?[[:space:]]*/dev/null##g; s#[0-9]*>&[0-9-]##g; s#(test|\[)[[:space:]]+-[a-z]([[:space:]])#\1 \2#g')
    if echo "$STRIPPED" | grep -qE '>' \
        || echo "$STRIPPED" | grep -qE '(^|[^[:alnum:]_.-])(tee|cp|mv|rm|ln|install|rsync|truncate|dd|touch|chmod|chown|ed|ex|vi|vim|nano)([[:space:]]|$)' \
        || echo "$STRIPPED" | grep -qE '[[:space:]](-e|-c|-p|--eval|--print)([[:space:]]|$)' \
        || echo "$STRIPPED" | grep -qE '(^|[[:space:]])(sed|gsed)[[:space:]].*-i'; then
        echo "Blocked: shell command that could write the stack trust store. $STORE_FIX" >&2
        exit 2
    fi
fi

# Keep patterns portable (POSIX classes, no empty alternatives): macOS grep rejects
# `(a|)`, and a grep error inside `if` reads as "no match" — silently allowing the command.

# Block rm targeting / or /* (but not ordinary absolute paths like /tmp/x)
if echo "$COMMAND" | grep -qE 'rm[[:space:]]+(-[-a-zA-Z]+[[:space:]]+)*/\*?([[:space:]]|$|[;&|])'; then
    echo "Blocked: recursive delete of root filesystem is not allowed." >&2
    exit 2
fi

# Block force pushes to protected branches: main, master, the remote's default branch
# (refs/remotes/<remote>/HEAD) and the globs in SDD_KIT_PROTECTED_BRANCHES (separated by spaces or
# commas). The variable only adds branches. Every git call tolerates a missing repository or git, so
# outside a repository the fixed names still apply. Keep this bash 3.2 compatible (macOS /bin/bash).
FORCE_FIX="Push to a feature branch and open a PR. Other branches can be protected with SDD_KIT_PROTECTED_BRANCHES (see Protected branches in the hooks README)."

# git -C <dir> <args>; prints nothing when the directory is no repository, git is missing or the ref is absent.
git_in() {
    local dir=$1
    shift
    git -C "$dir" "$@" 2>/dev/null || true
}

# Resolves directory $2 against base directory $1.
resolve_dir() {
    case "$2" in
        '~') printf '%s' "$HOME" ;;
        '~/'*) printf '%s/%s' "$HOME" "${2#\~/}" ;;
        /*) printf '%s' "$2" ;;
        *) printf '%s/%s' "$1" "$2" ;;
    esac
}

# Succeeds when branch $1 is protected for remote $3 of the repository at $2. Called while set -f is
# on, so the variable's globs match branch names and are never expanded against files.
is_protected() {
    local name=$1 default pattern patterns=() extra
    case "$name" in
        main|master) return 0 ;;
    esac
    default=$(git_in "$2" symbolic-ref --quiet --short "refs/remotes/$3/HEAD")
    default=${default#"$3"/}
    if [[ -n "$default" && "$name" == "$default" ]]; then
        return 0
    fi
    extra=${SDD_KIT_PROTECTED_BRANCHES:-}
    read -r -a patterns <<< "${extra//,/ }" || true
    for pattern in ${patterns[@]+"${patterns[@]}"}; do
        case "$name" in
            $pattern) return 0 ;;
        esac
    done
    return 1
}

# Prints the branches a wildcard destination $3 (such as `*` from refs/heads/*) reaches among main,
# master, the SDD_KIT_PROTECTED_BRANCHES entries, the local branches and the branches tracked from
# remote $2 of the repository at $1.
glob_targets() {
    local base=$1 remote=$2 pattern=$3 name extra names=()
    extra=${SDD_KIT_PROTECTED_BRANCHES:-}
    read -r -a names <<< "main master ${extra//,/ }" || true
    while IFS= read -r name; do
        names+=("$name")
    done <<< "$(git_in "$base" for-each-ref --format='%(refname:short)' refs/heads)"
    while IFS= read -r name; do
        names+=("${name#"$remote"/}")
    done <<< "$(git_in "$base" for-each-ref --format='%(refname:short)' "refs/remotes/$remote")"
    for name in "${names[@]}"; do
        if [[ -n "$name" && "$name" == $pattern ]]; then
            printf '%s\n' "$name"
        fi
    done
}

# Prints the protected branch that the git command in TOKENS (its words after `git` start at index $1)
# would force-push to, and nothing for any other command. $2 is the directory the command runs in.
# A command running an inline alias that can push prints `alias:<name>` instead: the alias expansion,
# and with it the target, cannot be read from the words.
forced_push_target() {
    local i=$1 base=$2 n=${#TOKENS[@]} tok j force='' all='' value_next='' options_done='' remote='' ref rforce dst
    local cfg key value matching='' alias_name=''
    local refs=() dests=() configs=()
    while (( i < n )); do
        tok=${TOKENS[i]}
        case "$tok" in
            -C) base=$(resolve_dir "$base" "${TOKENS[i + 1]:-.}"); i=$((i + 2)) ;;
            -c) configs+=("${TOKENS[i + 1]:-}"); i=$((i + 2)) ;;
            # --config-env names an environment variable the hook cannot read, so only its key is kept.
            --config-env) configs+=("${TOKENS[i + 1]%%=*}"); i=$((i + 2)) ;;
            --config-env=*) tok=${tok#--config-env=}; configs+=("${tok%%=*}"); i=$((i + 1)) ;;
            --git-dir|--work-tree|--namespace|--super-prefix|--attr-source) i=$((i + 2)) ;;
            -*) i=$((i + 1)) ;;
            *) break ;;
        esac
    done
    # A value that is unknown counts as the widest one: matching mode, or an alias that pushes.
    for cfg in ${configs[@]+"${configs[@]}"}; do
        key=$(printf '%s' "${cfg%%=*}" | tr '[:upper:]' '[:lower:]')
        value='push'
        if [[ "$cfg" == *=* ]]; then
            value=${cfg#*=}
        fi
        case "$key" in
            push.default)
                if [[ "$cfg" != *=* || "$value" == matching ]]; then
                    matching=1
                fi
                ;;
            remote.*.push|remote.*.mirror) matching=1 ;;
            alias.*)
                case "$value" in
                    push*|!*) alias_name=${key#alias.} ;;
                esac
                ;;
        esac
    done
    if [[ "${TOKENS[i]:-}" != push ]]; then
        if [[ -n "$alias_name" ]]; then
            printf 'alias:%s' "$alias_name"
        fi
        return 0
    fi
    if [[ "$(git_in "$base" config push.default)" == matching ]]; then
        matching=1
    fi
    i=$((i + 1))
    while (( i < n )); do
        tok=${TOKENS[i]}
        i=$((i + 1))
        if [[ -n "$value_next" ]]; then
            value_next=''
            continue
        fi
        if [[ -z "$options_done" ]]; then
            # git accepts any unambiguous prefix of a long option: --for covers --force, --force-with-lease
            # and --force-if-includes, --m is --mirror, --al is --all and --b is --branches.
            case "$tok" in
                --) options_done=1; continue ;;
                --for*) force=1; continue ;;
                --m*) force=1; all=1; continue ;;
                --al*|--b*) all=1; continue ;;
                --*=*) continue ;;
                --rep*|--pu*|--rece*|--e*) value_next=1; continue ;;
                -|--*) continue ;;
                -*)
                    # A short-option group: f forces; o takes the rest of the word, or the next word, as its value.
                    j=1
                    while (( j < ${#tok} )); do
                        case "${tok:j:1}" in
                            f) force=1 ;;
                            o)
                                if (( j + 1 == ${#tok} )); then
                                    value_next=1
                                fi
                                break
                                ;;
                        esac
                        j=$((j + 1))
                    done
                    continue
                    ;;
            esac
        fi
        if [[ -z "$tok" ]]; then
            continue
        elif [[ -z "$remote" ]]; then
            remote=$tok
        else
            refs+=("$tok")
        fi
    done
    remote=${remote:-origin}

    if [[ -n "$all" ]]; then
        if [[ -z "$force" ]]; then
            return 0
        fi
        while IFS= read -r ref; do
            if [[ -n "$ref" ]]; then
                dests+=("$ref")
            fi
        done <<< "$(git_in "$base" for-each-ref --format='%(refname:short)' refs/heads)"
        if [[ ${#dests[@]} -eq 0 ]]; then
            dests=(main master)
        fi
    elif [[ ${#refs[@]} -eq 0 ]]; then
        # With no refspec, push.default picks the target: the current branch or its upstream, or in
        # matching mode (or with an inline remote.<name>.push) every branch.
        if [[ -z "$force" ]]; then
            return 0
        fi
        if [[ -n "$matching" ]]; then
            dests=(main master)
            while IFS= read -r ref; do
                dests+=("$ref")
            done <<< "$(glob_targets "$base" "$remote" '*')"
        fi
        dests+=("$(git_in "$base" symbolic-ref --quiet --short HEAD)")
        dst=$(git_in "$base" rev-parse --abbrev-ref --symbolic-full-name '@{u}')
        dests+=("${dst#*/}")
    else
        for ref in "${refs[@]}"; do
            rforce=$force
            case "$ref" in
                +*) rforce=1; ref=${ref#+} ;;
            esac
            # An empty source deletes the destination, which is not a force push.
            if [[ -z "$rforce" || "$ref" == :* ]]; then
                continue
            fi
            # git expands a short destination such as heads/main through refs/%s, so it reaches refs/heads/main.
            dst=${ref#*:}
            case "$dst" in
                refs/heads/*) dst=${dst#refs/heads/} ;;
                heads/*) dst=${dst#heads/} ;;
            esac
            if [[ "$dst" == HEAD || "$dst" == @ ]]; then
                dst=$(git_in "$base" symbolic-ref --quiet --short HEAD)
            fi
            if [[ "$dst" == *\** ]]; then
                while IFS= read -r ref; do
                    dests+=("$ref")
                done <<< "$(glob_targets "$base" "$remote" "$dst")"
                continue
            fi
            dests+=("$dst")
        done
    fi

    for dst in ${dests[@]+"${dests[@]}"}; do
        if [[ -n "$dst" ]] && is_protected "$dst" "$base" "$remote"; then
            printf '%s' "$dst"
            return 0
        fi
    done
    return 0
}

# Line continuations are joined, then quotes and backslashes removed as in PLAIN, so "main" reads as main.
PUSH_TEXT=${COMMAND//$'\\\n'/ }
PUSH_TEXT=$(printf '%s' "$PUSH_TEXT" | tr -d "'\"\\\\")
# Only a command naming git, push and a force indicator pays for parsing and git calls.
if printf '%s\n' "$PUSH_TEXT" | grep -qE 'git.*push.*[[:space:]](--for|--m|-[[:alpha:]]*f|[+])'; then
    BASE_DIR=$(echo "$INPUT" | jq -r '.cwd // empty')
    BASE_DIR=${BASE_DIR:-$PWD}
    PROTECTED_TARGET=''
    set -f
    # Each segment between ; & | and newlines is read on its own; the last `cd` sets the directory later
    # segments run in. A git word anywhere in a segment counts, so sudo, env, bash -c and subshell forms
    # are covered. Quoted text is read as words too: a commit message naming a forced push is blocked.
    while IFS= read -r SEGMENT; do
        TOKENS=()
        read -r -a TOKENS <<< "$SEGMENT" || true
        K=0
        while (( K < ${#TOKENS[@]} )); do
            WORD=${TOKENS[K]##*[\(\`]}
            TOKENS[K]=${WORD%%[\)\`]*}
            K=$((K + 1))
        done
        if [[ "${TOKENS[0]:-}" == cd ]]; then
            BASE_DIR=$(resolve_dir "$BASE_DIR" "${TOKENS[1]:-$HOME}")
            continue
        fi
        K=0
        while (( K < ${#TOKENS[@]} )); do
            if [[ "${TOKENS[K]##*/}" == git ]]; then
                PROTECTED_TARGET=$(forced_push_target $((K + 1)) "$BASE_DIR" || true)
                if [[ -n "$PROTECTED_TARGET" ]]; then
                    break 2
                fi
            fi
            K=$((K + 1))
        done
    done < <(printf '%s\n' "$PUSH_TEXT" | tr ';&|' '\n\n\n')
    set +f
    if [[ "$PROTECTED_TARGET" == alias:* ]]; then
        echo "Blocked: possible force push to protected branch through the inline alias ${PROTECTED_TARGET#alias:}, whose target the guard cannot read. Fix: run git push itself instead of an alias set with -c. $FORCE_FIX" >&2
        exit 2
    elif [[ -n "$PROTECTED_TARGET" ]]; then
        echo "Blocked: force push to protected branch $PROTECTED_TARGET. $FORCE_FIX" >&2
        exit 2
    fi
fi

# Block drop database
if echo "$COMMAND" | grep -qiE '(drop[[:space:]]+database|dropdb)[[:space:]]'; then
    echo "Blocked: dropping databases requires manual confirmation." >&2
    exit 2
fi

exit 0
